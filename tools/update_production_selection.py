#!/usr/bin/env python3
"""Emit the production root selector for the admitted native Linux profiles (ADR 0054)."""
import argparse
import json
from pathlib import Path

import root_variants

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/linux_profiles.rs'
TARGET = ['target_os = "linux"', 'target_arch = "x86_64"', 'target_env = "gnu"']
# Every Cargo feature takes part in selection, so an unlisted feature set,
# including any AVM/AV2 selection, matches no profile.
FEATURES = root_variants.ORDER + ['avm']
PROFILES = {'release': 'not(debug_assertions)', 'debug': 'debug_assertions'}


def conditions(variant):
    selected = set(root_variants.features(variant))
    return [f'feature = "{name}"' if name in selected else f'not(feature = "{name}")' for name in FEATURES]


def pack(items, indent, width=100):
    """Wrap whole cfg predicates; a predicate is never split across lines."""
    lines, line = [], ''
    for item in items:
        candidate = f'{line}, {item}' if line else item
        if line and len(indent) + len(candidate) + 1 > width:
            lines.append(indent + line + ',')
            line = item
        else:
            line = candidate
    return '\n'.join(lines + [indent + line])


def selector(profile, variant):
    manifest = ROOT / f'translations/root-linux-{profile}-{variant}.json'
    if not manifest.is_file():
        raise SystemExit(f'Generate and validate the native Linux profile first: {manifest}')
    record = json.loads(manifest.read_text())
    path = Path(record['selector'])
    if (record.get('generation_target') != 'x86_64-unknown-linux-gnu' or record.get('preprocessing_profile') != profile
            or record.get('variant') != variant or path != Path(f'src/profiles/linux/{profile}/{variant}/modules.rs')):
        raise SystemExit(f'The native Linux profile manifest does not match its selector: {manifest}')
    return path.relative_to('src')


def render(variants=root_variants.LINUX_PRODUCTION):
    lines = ['// Generated by tools/update_production_selection.py; see ADR 0054.',
             '// The canonical Cargo feature set names the native profile variant.',
             '// `debug_assertions` selects original Debug preprocessing with enabled',
             '// assertions; otherwise the profile uses original Release (`NDEBUG`).',
             '#[cfg(not(any(']
    lines += ['    all(' + pack(conditions(variant), ' ' * 8)[8:] + '),' for variant in variants]
    admitted = ['[' + root_variants.cargo_features(variant).replace(',', ', ') + ']' for variant in variants]
    lines += [')))]', 'compile_error!(concat!(',
              '    "This Cargo feature set has no verified x86_64-unknown-linux-gnu production profile. ",',
              '    "Admitted feature sets: ",']
    lines += ['    ' + json.dumps(name + (', ' if index + 1 < len(admitted) else '. ')) + ','
              for index, name in enumerate(admitted)]
    lines += ['    "AVM/AV2 and other engine selections remain unverified; see ADR 0054.",', '));']
    for variant in variants:
        for profile, condition in PROFILES.items():
            lines += ['', '#[cfg(all(', pack(TARGET + [condition] + conditions(variant), '    '), '))]',
                      f'include!("{selector(profile, variant).as_posix()}");']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject a stale or edited production selector')
    args = parser.parse_args()
    text = render()
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit(f'The production root selector differs from its admitted profiles: {OUTPUT}')
        print(f'Production root selector matches {len(root_variants.LINUX_PRODUCTION)} admitted Linux configurations')
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
